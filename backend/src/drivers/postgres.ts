// Кэш размеров БД: pg_database_size медленный (сканирует файлы), обновляем раз в 30с
const pgSizeCache = new Map<string, { at: number; rows: { db: string; bytes: number }[] }>();

type Row = Record<string, unknown>;

/** pg хранит правила ссылочной целостности однобуквенными кодами, UI ждёт текст. */
const FK_ACTIONS: Record<string, string> = { a: 'NO ACTION', r: 'RESTRICT', c: 'CASCADE', n: 'SET NULL', d: 'SET DEFAULT' };

function fkAction(code: unknown): string | null {
  return FK_ACTIONS[String(code ?? '')] ?? null;
}

/**
 * string[] из колонки-массива pg. Массивы типа name[] pg отдаёт строкой
 * `{id,name}`, поэтому строки тоже разбираем. Пустой массив = нет колонок
 * (например, у expression-индекса, где attnum = 0).
 */
function strArray(v: unknown): string[] {
  if (Array.isArray(v)) return v.map((x) => String(x));
  if (typeof v === 'string' && v.startsWith('{') && v.endsWith('}')) {
    return v.slice(1, -1).split(',').map((x) => x.replace(/^"|"$/g, '')).filter((x) => x.length > 0);
  }
  return [];
}

/** Строки pg приходят с already-cast типами, но приводим к строкам явно. */
function optStr(v: unknown): string | null {
  return v === null || v === undefined || v === '' ? null : String(v);
}

/**
 * Квалификатор схемы в имени таблицы: `schema.table` или просто `table`.
 * Схема по умолчанию — public, обратной совместимости ради голое имя
 * трактуется как public. Имя схемы проверяется тем же ident(), точки внутри
 * имён не допускаются.
 */
function pgSplit(table: string): { schema: string; table: string } {
  const parts = String(table).split('.');
  if (parts.length === 1) return { schema: 'public', table: ident(parts[0], 'table') };
  if (parts.length === 2) return { schema: ident(parts[0], 'schema'), table: ident(parts[1], 'table') };
  throw Object.assign(new Error(`Bad table: ${table}`), { statusCode: 400 });
}

/** Квалифицированное имя `"schema"."table"` для DML/DDL. */
function qt(schema: string, table: string): string {
  return `"${schema}"."${table}"`;
}

/**
 * pg_attribute.attidentity — «char»-поле: 'a' = GENERATED ALWAYS AS IDENTITY,
 * 'd' = GENERATED BY DEFAULT AS IDENTITY. Отдаём слово, а не символ.
 */
function identityKind(v: string | null): string | null {
  if (v === 'a') return 'ALWAYS';
  if (v === 'd') return 'BY DEFAULT';
  return v;
}

/** DDL-стейтмент в транзакции на одном соединении: в pg ошибка сама по себе
 *  откатывает только текущий стейтмент, поэтому BEGIN/COMMIT ставлю явно —
 *  так поведение совпадает с alterTable. */
async function runDdl(p: ReturnType<typeof getPgPool>, statement: string): Promise<void> {
  const client = await p.connect();
  try {
    await client.query('BEGIN');
    await client.query(statement);
    await client.query('COMMIT');
  } catch (e) {
    await client.query('ROLLBACK').catch(() => undefined);
    throw e;
  } finally {
    client.release();
  }
}

