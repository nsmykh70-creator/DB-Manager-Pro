/**
 * Диалект по виду подключения из API (`DbKind`).
 *
 * Живёт здесь, а не в компонентах: и конструктор, и карточка таблицы должны
 * показывать один и тот же набор типов для одной и той же СУБД. Redis и MongoDB
 * диалектных типов строк не имеют — им возвращаем mysql, чтобы списки типов
 * оставались непустыми, а сами операции изменения структуры для них и так
 * запрещены на сервере.
 */
export function dialectForKind(kind?: string): SupportedDbDialect {
  if (kind === 'postgres') return 'postgresql';
  if (kind === 'sqlite') return 'sqlite';
  if (kind === 'mongodb') return 'mongodb';
  if (kind === 'redis') return 'redis';
  if (kind === 'mariadb') return 'mariadb';
  if (kind === 'oracle') return 'oracle';
  return 'mysql';
}

/**
 * Detect database dialect by database name or fallback to mysql
 */
export function detectDatabaseType(dbName: string = ''): SupportedDbDialect {
  const lower = dbName.toLowerCase();
  if (lower.includes('pg') || lower.includes('postgres') || lower.includes('main_db') || lower.includes('analytics_db')) {
    return 'postgresql';
  }
  if (lower.includes('redis') || lower.includes('cache')) {
    return 'redis';
  }
  if (lower.includes('sqlite') || lower.includes('app_db') || lower.endsWith('.db') || lower.endsWith('.sqlite')) {
    return 'sqlite';
  }
  if (lower.includes('mongo') || lower.includes('users_db') || lower.includes('logs_db')) {
    return 'mongodb';
  }
  if (lower.includes('maria') || lower.includes('dev_db')) {
    return 'mariadb';
  }
  return 'mysql';
}
